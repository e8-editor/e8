#!/usr/bin/env python3
"""Writes geometry.rs, the guided field's coordinates, from the drawing in
docs/assets/lattices/guided-field.svg (ADR 0106), for the GUI to draw it
at startup (ADR 0108).

The SVG is the drawing as the brand ships it, traced from
docs/assets/lattices/source/guided-reference-trace.json: its lines, each a
`<path d="Mx yLx y">` with an opacity, the highlighted path as one
`<polyline>`, and its dots as `<circle>`s, Lavender ones on the path.
Colours are left behind: the GUI takes them from its tokens.

Run it from anywhere after the drawing changes:
    python3 crates/e8-gui/src/lattice/make-geometry.py
"""

import os
import re

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, "..", "..", "..", "..")
svg = open(os.path.join(root, "docs", "assets", "lattices", "guided-field.svg")).read()

width, height = (int(v) for v in re.search(r'<svg[^>]*width="(\d+)" height="(\d+)"', svg).groups())
lines = [
    (float(x1), float(y1), float(x2), float(y2), float(opacity), float(stroke))
    for x1, y1, x2, y2, stroke, opacity in re.findall(
        r'<path d="M([\d.]+) ([\d.]+)L([\d.]+) ([\d.]+)"[^>]*stroke-width="([\d.]+)" opacity="([\d.]+)"', svg
    )
]
polylines = re.findall(r'<polyline points="([^"]+)"[^>]*stroke-width="([\d.]+)"', svg)
assert len(polylines) == 1, "the guided field has one path"
path = [tuple(float(v) for v in p.split(",")) for p in polylines[0][0].split()]
path_width = float(polylines[0][1])
accent = re.search(r'<polyline[^>]*stroke="(#[0-9A-Fa-f]+)"', svg).group(1)
dots = [
    (float(x), float(y), float(r), fill.upper() == accent.upper())
    for x, y, r, fill in re.findall(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)" fill="(#[0-9A-Fa-f]+)"', svg)
]
assert len(lines) == svg.count("<path") and len(dots) == svg.count("<circle"), "every element was read"
assert len({s for *_, s in lines}) == 1, "the lines are one width"
assert all(b[0] > a[0] for a, b in zip(path, path[1:])), "the path runs left to right"


def f(v):
    return f"{v:.1f}"


out = [
    "// Generated by make-geometry.py from docs/assets/lattices/guided-field.svg; do not edit.",
    "",
    "/// The drawing's box, in its own units.",
    f"pub const SIZE: [f32; 2] = [{f(width)}, {f(height)}];",
    "/// How wide the lines are drawn, in the drawing's units.",
    f"pub const LINE_WIDTH: f32 = {f(lines[0][5])};",
    "/// How wide the path is drawn, in the drawing's units.",
    f"pub const PATH_WIDTH: f32 = {f(path_width)};",
    "",
    "/// The field's lines: from, to, and how strongly each is drawn, some fainter than the rest.",
    f"pub const LINES: [([f32; 2], [f32; 2], f32); {len(lines)}] = [",
]
out += [f"    ([{f(a)}, {f(b)}], [{f(c)}, {f(d)}], {o:g}{'' if o != int(o) else '.0'})," for a, b, c, d, o, _ in lines]
out += [
    "];",
    "",
    "/// The highlighted path through the field, left to right.",
    f"pub const PATH: [[f32; 2]; {len(path)}] = [",
]
out += [f"    [{f(x)}, {f(y)}]," for x, y in path]
out += [
    "];",
    "",
    "/// The field's dots: centre, radius, and whether it is drawn in the accent, as the path is.",
    f"pub const DOTS: [([f32; 2], f32, bool); {len(dots)}] = [",
]
out += [f"    ([{f(x)}, {f(y)}], {f(r)}, {'true' if a else 'false'})," for x, y, r, a in dots]
out += ["];", ""]
open(os.path.join(here, "geometry.rs"), "w").write("\n".join(out))
print(f"{len(lines)} lines, {len(dots)} dots, a path of {len(path)} points")
